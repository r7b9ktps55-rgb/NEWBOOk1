FORMATS: dict[str, Format] = {
    f.id: f
    for f in [
        Format("summary", "Подробный конспект", "", SUMMARY),
        Format("brief", "Кратко на 1 страницу", "кратко", BRIEF),
        Format("key", "Ключевые моменты", "ключевые моменты", KEY_POINTS),
        Format("quotes", "Лучшие цитаты по темам", "цитаты", QUOTES),
        Format("characters", "Герои (ГГ и персонажи)", "герои", CHARACTERS),
        Format("cards", "Карточки для повторения", "карточки", CARDS),
        Format("x2", "Сжатие ×2", "сжатие x2", ratio=2),
        Format("x3", "Сжатие ×3", "сжатие x3", ratio=3),
        Format("x4", "Сжатие ×4", "сжатие x4", ratio=4),
        Format("x5", "Сжатие ×5", "сжатие x5", ratio=5),
    ]
}


def parse_formats(values, default: list[str] | None = None) -> list[str]:
    """Оставляет только известные форматы, без повторов, в порядке FORMATS."""
    if isinstance(values, str):
        values = values.split(",")
    wanted = {v.strip() for v in values or [] if v and v.strip()}
    picked = [f for f in FORMATS if f in wanted]
    return picked or list(default or ["summary"])


def compress_prompt(ratio: int, words: int, part: int, total: int, first: bool, book: str | None) -> str:
    lines = []
    if first and not book:
        lines.append("Первая строка ответа строго: FILENAME: <Название книги> - <Автор> (если неизвестно — «Неизвестно»).")
        lines.append("Со второй строки — сам пересказ.")
    where = f"книги «{book}»" if book else "книги"
    lines.append(
        f"Перед тобой часть {part} из {total} {where}. Перескажи её на русском языке, сократив примерно в {ratio} раза — "
        f"до {words} слов (±15%)."
    )
    lines.append(
        "Сохраняй авторский голос и порядок изложения: события, аргументы, ключевые примеры, имена, термины, "
        "числа и самые важные фразы (их можно оставлять дословно). Ничего не добавляй от себя и не пиши вступлений "
        "вроде «В этом фрагменте». Пиши связным текстом в Markdown; если в части начинается новая глава — "
        "поставь заголовок `## Название главы`. Без frontmatter и без блока кода."
    )
    return "\n".join(lines)
